export type AuthCopy = (typeof copy)['en']

export const AUTH_LANG_COOKIE = 'ik-lang'

export function useAuthLocale() {
  const cookie = useCookie<AuthLocale>(AUTH_LANG_COOKIE, {
    default: () => 'en',
    maxAge: 60 * 60 * 24 * 365,
    sameSite: 'lax',
  })
  const locale = computed<AuthLocale>(() => (cookie.value === 'ms' ? 'ms' : 'en'))
  const t = computed(() => copy[locale.value] as AuthCopy)
  function setLocale(next: AuthLocale) {
    cookie.value = next
  }
  return { locale, t, setLocale }
}

/** 0 too short · 1 okay · 2 good · 3 strong. Matches the 8-character rule. */
export function passwordScore(pw: string) {
  if (pw.length < 8) return 0
  let s = 1
  if (/\d/.test(pw)) s++
  if (/[^A-Za-z0-9]/.test(pw) || (/[a-z]/.test(pw) && /[A-Z]/.test(pw))) s++
  return s
}
